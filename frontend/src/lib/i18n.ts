export function translateUiText(source: string, locale: Locale) {
  if (locale === "zh") return source;
  const exact = UI_TRANSLATIONS[source];
  if (exact) return exact;
  for (const [pattern, replace] of UI_PATTERNS) {
    const match = source.match(pattern);
    if (match) return replace(...match);
  }
  return source;
}

const REVERSE_TRANSLATIONS = new Map(Object.entries(UI_TRANSLATIONS).map(([zh, en]) => [en, zh]));

export function recoverSourceText(value: string) {
  return REVERSE_TRANSLATIONS.get(value) ?? value;
}
